// Release signing: keystore.properties (local, git-ignored) or environment variables (CI).
val signingProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String, env: String): String? =
    signingProps.getProperty(key) ?: System.getenv(env)?.takeIf { it.isNotBlank() }

val releaseStoreFile = signingValue("storeFile", "SIGNING_STORE_FILE")

android {
    namespace = "com.iqbal.seatwatcher"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.iqbal.seatwatcher"
